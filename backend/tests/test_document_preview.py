def _all_paragraphs(blocks):
    """Top-level paragraphs and every cell paragraph, in document order."""
    for block in blocks:
        if block["kind"] == "paragraph":
            yield block
            continue
        for row in block["rows"]:
            for cell in row:
                yield from cell["paragraphs"]


def _block_text(block) -> str:
    if block["kind"] == "paragraph":
        return _para_text(block)
    return "|".join(
        _para_text(p) for row in block["rows"] for cell in row for p in cell["paragraphs"]
    )


def _paragraph_starting(blocks, prefix: str, *, style: str | None = None) -> dict:
    """The first top-level paragraph starting with ``prefix`` — of ``style``
    when given, since the index repeats every heading's text in Normal."""
    return next(
        b
        for b in blocks
        if b["kind"] == "paragraph"
        and _para_text(b).startswith(prefix)
        and (style is None or b["style"] == style)
    )


def _project(actual, like):
    """``actual`` restricted to the keys ``like`` has, recursively."""
    if isinstance(like, dict):
        return {key: _project(actual[key], value) for key, value in like.items()}
    if isinstance(like, list) and isinstance(actual, list) and len(actual) == len(like):
        return [_project(a, b) for a, b in zip(actual, like)]
    return actual


def _set_num_pr(paragraph, *, num_id: int, ilvl: int | None = None) -> None:
    num_pr = paragraph._p.get_or_add_pPr().get_or_add_numPr()
    if ilvl is not None:
        num_pr.get_or_add_ilvl().val = ilvl
    num_pr.get_or_add_numId().val = num_id


def _append_numbering(doc, abstract_xml: str, num_xml: str) -> None:
    """Add a w:abstractNum (before the w:num elements, as the schema orders
    them) and a w:num to the document's numbering part."""
    numbering = doc.part.numbering_part.element
    numbering.find(qn("w:num")).addprevious(parse_xml(abstract_xml))
    numbering.append(parse_xml(num_xml))


def _add_two_level_numbering(doc) -> int:
    """List 90: a real "▪" at level 0 and "%2)" at level 1. Returns its numId."""
    w = nsdecls("w")
    _append_numbering(
        doc,
        f'<w:abstractNum {w} w:abstractNumId="90">'
        '<w:multiLevelType w:val="hybridMultilevel"/>'
        '<w:lvl w:ilvl="0"><w:start w:val="1"/><w:numFmt w:val="bullet"/><w:lvlText w:val="▪"/></w:lvl>'
        '<w:lvl w:ilvl="1"><w:start w:val="1"/><w:numFmt w:val="decimal"/><w:lvlText w:val="%2)"/></w:lvl>'
        "</w:abstractNum>",
        f'<w:num {w} w:numId="90"><w:abstractNumId w:val="90"/></w:num>',
    )
    return 90


def _set_v_align(cell, value: str) -> None:
    v_align = OxmlElement("w:vAlign")
    v_align.set(qn("w:val"), value)
    cell._tc.get_or_add_tcPr().append(v_align)


def _set_mark_color(paragraph, value: str) -> None:
    """Colour of the paragraph mark (pPr/rPr), as Word writes it."""
    rpr = OxmlElement("w:rPr")
    color = OxmlElement("w:color")
    color.set(qn("w:val"), value)
    rpr.append(color)
    paragraph._p.get_or_add_pPr().append(rpr)


